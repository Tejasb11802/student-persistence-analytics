-- Student Persistence & At-Risk Analytics: SQLite schema
DROP TABLE IF EXISTS learners;
CREATE TABLE learners (
    student_id                  TEXT PRIMARY KEY,
    age                         INTEGER,
    gender                      TEXT,
    first_generation            INTEGER,
    pell_eligible               INTEGER,
    residency                   TEXT,
    enrollment_status           TEXT,
    modality                    TEXT,
    college                     TEXT,
    housing                     TEXT,
    work_hours_per_week         REAL,
    hs_gpa                      REAL,
    term_gpa                    REAL,
    credits_attempted           INTEGER,
    credits_earned              INTEGER,
    lms_logins_wk1_4            REAL,
    lms_logins_wk5_8            REAL,
    avg_session_minutes         REAL,
    assignment_submission_rate  REAL,
    late_submission_rate        REAL,
    forum_posts                 INTEGER,
    days_since_last_login       INTEGER,
    advising_visits             INTEGER,
    tutoring_sessions           INTEGER,
    financial_hold              INTEGER,
    scholarship                 INTEGER,
    distance_from_campus_miles  REAL,
    zip_prefix                  INTEGER,
    orientation_attended        INTEGER,
    email_open_rate             REAL,
    parking_permit              INTEGER,
    persisted_next_term         INTEGER
);
